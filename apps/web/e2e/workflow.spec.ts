test('real multipart import validates locally then publishes a usable snapshot',async ({ page }) => {
  const directory = resolve(root,'data/generated/seed-20261010/03c9ef66-2609-5aec-86fa-9dda41e1c9af')
  const manifest = JSON.parse(readFileSync(resolve(directory,'manifest.json'),'utf8'))
  manifest.episode_id = crypto.randomUUID()
  await page.goto('/admin/imports')
  await connect(page)
  await page.getByLabel('Manifest JSON').setInputFiles({ name:'manifest.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(manifest)) })
  await page.getByLabel('Declared source files').setInputFiles(manifest.sources.map((s: {logical_name:string}) => resolve(directory,s.logical_name)))
  await page.getByRole('button',{ name:'Validate locally' }).click()
  await expect(page.getByText(/Local manifest\/hash checks passed/)).toBeVisible()
  await page.getByRole('button',{ name:'Submit import',exact:true }).click()
  await page.getByRole('link',{ name:'Open imported episode' }).click({ timeout:30000 })
  await expect(page.getByRole('heading',{ name:'Observed dependencies' })).toBeVisible()
})

